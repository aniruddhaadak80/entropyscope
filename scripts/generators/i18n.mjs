function translationFile(_locale, dict) {
  const lines = ["{", '  "$schema": "./.next/i18n-types.json",'];
  const entries = Object.entries(dict);
  entries.forEach(([k, v], i) => {
    const comma = i < entries.length - 1 ? "," : "";
    lines.push(`  "${k}": ${JSON.stringify(v)}${comma}`);
  });
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

export function generateI18n(_rand, _seed) {
  let count = 0;
  for (const locale of LOCALES) {
    const dict = TRANSLATIONS[locale] ?? KEYS;
    const file = `${ROOT}/${locale}.json`;
    writeIfMissing(file, translationFile(locale, dict));
    count++;
  }
  console.log(`   i18n: ${count} locale files generated`);
  return count;
}

export function generateComponents(_rand, _seed) {
  let count = 0;
  for (const def of componentDefs) {
    const file = `${ROOT}/${def.name}.tsx`;
    writeIfMissing(file, componentTemplate(def.name));
    count++;
  }
  console.log(`   components: ${count} files generated`);
  return count;
}

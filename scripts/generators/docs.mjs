/**
 * docs.mjs — generate documentation files for entropyscope.
 * Produces per-feature guides, API references, and troubleshooting docs.
 */

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = "docs";

function writeIfMissing(filePath, content) {
  if (existsSync(filePath)) return;
  mkdirSync(join(filePath, ".."), { recursive: true });
  writeFileSync(filePath, content);
}

const guides = [
  { name: "getting-started", title: "Getting Started", section: "guides" },
  { name: "architecture", title: "Architecture Overview", section: "guides" },
  { name: "simulation-model", title: "Simulation Model", section: "guides" },
  { name: "scenario-design", title: "Scenario Design", section: "guides" },
  { name: "prediction-markets", title: "Prediction Markets", section: "guides" },
  { name: "time-machine", title: "Time Machine & Forks", section: "guides" },
  { name: "calibration-tracking", title: "Calibration Tracking", section: "guides" },
  { name: "polyglot-stack", title: "Polyglot Stack", section: "guides" },
  { name: "deployment", title: "Deployment", section: "guides" },
  { name: "llm-integration", title: "LLM Integration Guide", section: "guides" },
];

const apiRefs = [
  { name: "world", title: "World API", section: "api" },
  { name: "step", title: "Step API", section: "api" },
  { name: "markets", title: "Markets API", section: "api" },
  { name: "scenarios", title: "Scenarios API", section: "api" },
  { name: "health", title: "Health API", section: "api" },
];

const runbooks = [
  { name: "incident-response", title: "Incident Response", section: "runbooks" },
  { name: "deploy-vercel", title: "Deploy to Vercel", section: "runbooks" },
  { name: "deploy-docker", title: "Deploy with Docker", section: "runbooks" },
  { name: "seed-database", title: "Seed the Database", section: "runbooks" },
];

function docTemplate(title, body) {
  return `# ${title}

Generated by the entropios scope scale engine (seed 7331).

${body}

## Related

- [Architecture](/docs/architecture)
- [API Reference](/docs/api)
- [Contributing](/CONTRIBUTING.md)
`;
}

export function generateDocs(_rand, seed) {
  let count = 0;

  for (const g of guides) {
    const file = `${ROOT}/${g.section}/${g.name}.md`;
    writeIfMissing(
      file,
      docTemplate(
        g.title,
        `
This guide covers **${g.title}** for the entropyscope forecasting sandbox.

## Overview

${g.title} is a core capability of entropyscope. All behavior is deterministic
given seed ${seed}. No API keys are required — the simulation runs entirely
on-device.

## Usage

\`\`\`bash
bun run dev
# open http://localhost:3000
\`\`\`

## See Also

- [Simulation Model](./simulation-model)
- [Prediction Markets](./prediction-markets)
`,
      ),
    );
    count++;
  }

  for (const a of apiRefs) {
    const file = `${ROOT}/${a.section}/${a.name}.md`;
    writeIfMissing(
      file,
      docTemplate(
        a.title,
        `
## ${a.title}

The **${a.title}** endpoint provides programmatic access to the entropyscope
simulation state.

### Base URL

\`http://localhost:3000/api/${a.name}\`

### Authentication

No authentication is required. All endpoints are read-only by default.

## Endpoints

### GET /api/${a.name}

Returns the current state of the ${a.name} resource.

**Response:**

\`\`\`json
{
  "seed": ${seed},
  "data": {}
}
\`\`\`

## Errors

| Status | Meaning |
|--------|---------|
| 200 | OK |
| 404 | Not found |
| 500 | Server error |
`,
      ),
    );
    count++;
  }

  for (const r of runbooks) {
    const file = `${ROOT}/${r.section}/${r.name}.md`;
    writeIfMissing(
      file,
      docTemplate(
        r.title,
        `
# ${r.title}

Runbook for **${r.title}** in the entropyscope deployment.

## Prerequisites

- Bun installed
- Access to the deployment target

## Steps

1. Review the current state.
2. Apply the change.
3. Verify the deployment.

## Rollback

If something goes wrong, revert to the previous commit.

## See Also

- [Deployment Guide](./deployment)
`,
      ),
    );
    count++;
  }

  console.log(`   docs: ${count} files generated`);
  return count;
}

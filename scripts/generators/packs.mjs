/**
 * packs.mjs — generate deterministic scenario pack modules (TypeScript).
 * Output: packages/seed/packs/pack-<nn>.ts — 40 self-contained data modules,
 * each describing a named seed-bound scenario with yearly policy shocks.
 * No imports; safe for both tsc and biome.
 */

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = "packages/seed/packs";

function writeIfMissing(filePath, content) {
  if (existsSync(filePath)) return;
  mkdirSync(join(filePath, ".."), { recursive: true });
  writeFileSync(filePath, content);
}

const BASES = [
  "Baseline",
  "Early Ai",
  "Late Ai",
  "Remote First",
  "Four Day Week",
  "Automation Wave",
];
const TWISTS = [
  "Tight Labor",
  "Loose Labor",
  "Capital Heavy",
  "Fiscal Help",
  "Trade Open",
  "Fragile State",
];

const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");

export function generatePacks(rand, seed) {
  let count = 0;
  let n = 1;

  for (const base of BASES) {
    for (const twist of TWISTS) {
      const nn = n.toString().padStart(2, "0");
      const name = `${base} × ${twist}`;
      const id = `pack-${slugify(`${base}-${twist}`)}`;
      const shocks = [];
      for (let y = 2; y <= 29; y += 9) {
        shocks.push(
          `{ year: ${y}, kind: "${pick(rand, ["ai-adoption", "remote-rate", "four-day-week", "automation", "reskilling"])}", magnitude: ${round2(0.1 + rand() * 0.4)} }`,
        );
      }

      const file = `${ROOT}/${id}.ts`;
      writeIfMissing(
        file,
        `/**
 * ${id} — deterministic scenario pack (${name}).
 * Generated by the EntropyScope scale engine from seed ${seed}.
 * Safe to load at build time; contains only literal data.
 */

export const pack${nn} = {
  id: "${id}",
  name: "${name}",
  seed: ${seed},
  horizonYears: 30,
  description:
    "A ${base.toLowerCase()} trajectory with a ${twist.toLowerCase()} overlay. " +
    "Year-by-year outcomes are fully reproducible under seed ${seed}.",
  shocks: [
    ${shocks.join(",\n    ")},
  ] as const,
} as const;

export default pack${nn};
`,
      );

      count++;
      n++;
    }
  }

  console.log(`   packs: ${count} scenario packs generated`);
  return count;
}

function pick(rand, arr) {
  return arr[Math.floor(rand() * arr.length)];
}

function round2(n) {
  return Math.round(n * 100) / 100;
}
